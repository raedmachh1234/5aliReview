// Compiles src/content/legal/<locale>/*.md into a TypeScript module so the
// default legal texts are bundled with the app (no runtime filesystem reads).
// Runs automatically before `dev` and `build` (see package.json).
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const root = join(process.cwd(), "src", "content", "legal");
const out = join(root, "defaults.generated.ts");
const docs = {};

for (const locale of readdirSync(root, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name)) {
  for (const file of readdirSync(join(root, locale)).filter((f) => f.endsWith(".md"))) {
    const slug = file.replace(/\.md$/, "");
    const body = readFileSync(join(root, locale, file), "utf8").replace(/\r\n/g, "\n");
    const title = /^#\s+(.+)$/m.exec(body)?.[1]?.trim() ?? slug;
    docs[locale] ??= {};
    docs[locale][slug] = { title, bodyMd: body };
  }
}

const content = `// AUTO-GENERATED by scripts/build-legal-content.mjs — edit the .md files instead.
import type { LegalSlug, Locale } from "@/lib/types";

export const legalDefaults: Partial<Record<Locale, Partial<Record<LegalSlug, { title: string; bodyMd: string }>>>> = ${JSON.stringify(docs, null, 2)};
`;
if (!existsSync(out) || readFileSync(out, "utf8") !== content) writeFileSync(out, content);
console.log(`legal content: ${Object.values(docs).reduce((n, d) => n + Object.keys(d).length, 0)} documents`);
